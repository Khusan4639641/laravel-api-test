export function adminText(key: string) {
  const source = adminRuText[key] || key;
  const language = normalizeLanguage(i18n.resolvedLanguage || i18n.language);

  if (language === 'ru') {
    return source;
  }

  return localizedAdminPhrase(adminPhraseTranslations[source], language, source)
    || translateAdminPattern(source, language)
    || translateRuntimeLiteral(source, language);
}

function localizedAdminPhrase(entry: AdminPhraseTranslation | undefined, language: SupportedLanguage, source?: string) {
  if (!entry) {
    return undefined;
  }

  if (language === 'kg' && source) {
    const runtimeTranslation = translateRuntimeLiteral(source, language);

    if (runtimeTranslation !== source) {
      return runtimeTranslation;
    }
  }

  return entry[language]
    || (language !== 'ru' ? entry.en : undefined)
    || entry.ru;
}

